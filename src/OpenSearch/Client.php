     * Extract an argument from the array of parameters
     *
     * @return null|mixed
     */
    public function extract_argument(array &$params, string $arg)
    {
        if (array_key_exists($arg, $params) === true) {
            $value = $params[$arg];
            $value = is_object($value) && !is_iterable($value) ? (array) $value : $value;
            unset($params[$arg]);
            return $value;
        }
        return null;
    }
